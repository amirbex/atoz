#!/usr/bin/env python3
"""Package the generated brand slides as a presentation PDF and asset index."""
from __future__ import annotations
import json
from pathlib import Path
from reportlab.pdfgen import canvas
from reportlab.lib.units import inch
from reportlab.lib.utils import ImageReader

ROOT=Path(__file__).resolve().parents[1]
BOOK=ROOT/"brand/brand-book"
SLIDES=BOOK/"slides"
OUT=BOOK/"brand-book.pdf"


def main():
    slides=sorted(SLIDES.glob("slide-*.png"))
    if len(slides)!=12:
        raise SystemExit(f"Expected 12 rendered slides, found {len(slides)}. Run the brand builder and renderer first.")
    for path in slides:
        if path.stat().st_size==0: raise SystemExit(f"Empty slide render: {path}")
    width,height=16*inch,9*inch
    pdf=canvas.Canvas(str(OUT),pagesize=(width,height),pageCompression=1)
    pdf.setTitle("AtoZ.FnB — Brand Book 2.0 (Review Edition)")
    pdf.setAuthor("AtoZ.FnB")
    pdf.setSubject("Foundational visual identity, sections, typography, templates and motion principles")
    for path in slides:
        pdf.drawImage(ImageReader(str(path)),0,0,width=width,height=height,mask="auto",preserveAspectRatio=False)
        pdf.showPage()
    pdf.save()

    templates=json.loads((ROOT/"content-templates/template-manifest.json").read_text(encoding="utf-8"))
    fonts=json.loads((ROOT/"brand/fonts/font-inventory.json").read_text(encoding="utf-8"))
    motions=sorted((ROOT/"logo-motion").glob("exports/*.mp4"))
    index={
      "version":"2.0.0-draft",
      "phase":"foundational_identity_assets_only",
      "book":{"pdf":str(OUT.relative_to(ROOT)),"html":"brand/brand-book/brand-book.html","slide_count":len(slides),"source_directory":"brand/brand-book/slides/"},
      "sheets":[str(p.relative_to(ROOT)) for p in sorted((ROOT/"brand/sheets").glob("*.png"))],
      "templates":{"manifest":"content-templates/template-manifest.json","count":len(templates["templates"]),"source_directory":"content-templates/"},
      "logo_motion":[str(p.relative_to(ROOT)) for p in motions],
      "font_audit":{"inventory":"brand/fonts/font-inventory.json","files_audited":fonts["font_count"],"unverified_font_families_not_embedded":True},
      "scope_note":"No editorial content package, upload, schedule, web deployment, or publication is generated by this asset phase. Owner review required."
    }
    (ROOT/"brand/asset-index.json").write_text(json.dumps(index,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(slides)} slides, {OUT.stat().st_size/1024/1024:.1f} MiB)")

if __name__=="__main__":main()
